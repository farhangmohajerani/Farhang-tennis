export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let s = (lang === 'fa' ? fa[key] : undefined) ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), formatNum(lang, v));
  return s;
}

export function formatNum(lang: Lang, v: string | number): string {
  if (typeof v === 'number' && lang === 'fa') return v.toLocaleString('fa-IR');
  return String(v);
}

export const catLabel = (lang: Lang, c: Category) => CAT[lang][c];
export const levelLabel = (lang: Lang, l: Level) => LVL[lang][l];
export const roleKey = (r: Role): DictKey => `role_${r}` as DictKey;
export const kpiKey = (k: KpiKey): DictKey => `kpi_${k}` as DictKey;

export function formatDate(lang: Lang, iso: string, opts: Intl.DateTimeFormatOptions = { weekday: 'short', day: 'numeric', month: 'short' }): string {
  const [y, m, d] = iso.split('-').map(Number);
  const date = new Date(y, m - 1, d);
  try {
    return new Intl.DateTimeFormat(lang === 'fa' ? 'fa-IR' : 'en-GB', opts).format(date);
  } catch {
    return iso;
  }
}

